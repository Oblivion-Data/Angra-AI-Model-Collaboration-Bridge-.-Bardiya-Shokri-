PLUGIN_TOOLS_TS = r'''import { tool, Tool, ToolsProviderController, LMStudioClient } from "@lmstudio/sdk";
import { z } from "zod";
import { appendFile, mkdir, readFile, rename, writeFile } from "fs/promises";
import { dirname } from "path";
import { ANGRA_STATE_PATH, ANGRA_LOG_PATH } from "./angraPaths";

interface Safety {
  max_active_helpers: number;
  parallel_helpers: boolean;
  max_helper_calls_per_response: number;
  recursive_delegation: boolean;
  max_helper_context: number;
  max_helper_output: number;
  timeout_seconds: number;
  cooldown_seconds: number;
}
interface Permission {
  mode?: string;
  expires_at?: number | null;
}
interface AngraState {
  primary: string | null;
  links: Record<string, string[]>;
  permissions: Record<string, Permission>;
  safety: Safety;
}

const FALLBACK_SAFETY: Safety = {
  max_active_helpers: 1,
  parallel_helpers: false,
  max_helper_calls_per_response: 1,
  recursive_delegation: false,
  max_helper_context: 4096,
  max_helper_output: 512,
  timeout_seconds: 90,
  cooldown_seconds: 5,
};

// Single-flight guard: only one helper call at a time, no parallel inference.
let busy = false;
let lastCallAt = 0;

async function logEvent(event: string, detail: Record<string, unknown>): Promise<void> {
  // Metadata only. Never log task text, context or model answers.
  try {
    await mkdir(dirname(ANGRA_LOG_PATH), { recursive: true });
    const line = JSON.stringify({ ts: new Date().toISOString(), event, ...detail }) + "\n";
    await appendFile(ANGRA_LOG_PATH, line, "utf-8");
  } catch {
    /* logging must never break a tool call */
  }
}

async function readState(): Promise<AngraState> {
  const raw = JSON.parse(await readFile(ANGRA_STATE_PATH, "utf-8"));
  return {
    primary: typeof raw.primary === "string" ? raw.primary : null,
    links: raw.links && typeof raw.links === "object" ? raw.links : {},
    permissions: raw.permissions && typeof raw.permissions === "object" ? raw.permissions : {},
    safety: { ...FALLBACK_SAFETY, ...(raw.safety ?? {}) },
  };
}

async function consumeOnce(key: string): Promise<void> {
  const raw = JSON.parse(await readFile(ANGRA_STATE_PATH, "utf-8"));
  const p = raw.permissions?.[key];
  if (!p || p.mode !== "once") {
    throw new Error("one-time permission is no longer available");
  }
  p.mode = "off";
  p.expires_at = null;
  p.consumed_at = Date.now() / 1000;
  raw.updated_at = new Date().toISOString();
  const tmp = ANGRA_STATE_PATH + ".plugin.tmp";
  await writeFile(tmp, JSON.stringify(raw, null, 2), "utf-8");
  await rename(tmp, ANGRA_STATE_PATH);
}

function permissionOk(p: Permission | undefined): { ok: boolean; mode: string } {
  const mode = (p?.mode ?? "off").toLowerCase();
  if (mode === "enabled" || mode === "once") return { ok: true, mode };
  if (mode === "session") {
    const exp = p?.expires_at;
    if (typeof exp === "number" && Date.now() / 1000 < exp) return { ok: true, mode };
    return { ok: false, mode: "session-expired" };
  }
  return { ok: false, mode };
}

function handleKeys(h: any): string[] {
  return [h?.modelKey, h?.identifier, h?.path].filter(
    (v: unknown) => typeof v === "string" && (v as string).length > 0,
  ) as string[];
}
function sameModel(h: any, key: string): boolean {
  const k = key.trim().toLowerCase();
  return handleKeys(h).some((v) => v.toLowerCase() === k);
}

// Enumerates models that are ALREADY loaded. This never loads anything.
async function listLoadedHandles(client: LMStudioClient): Promise<any[]> {
  return (await client.llm.listLoaded()) as any[];
}

function denied(reason: string, message: string, extra: Record<string, unknown> = {}) {
  return { status: "denied", reason, message, angra_inference: "none", ...extra };
}

export async function toolsProvider(ctl: ToolsProviderController) {
  const client: LMStudioClient = (ctl as any).client ?? new LMStudioClient();
  const tools: Tool[] = [];

  tools.push(
    tool({
      name: "angra_status",
      description:
        "Report Angra bridge status: the user's declared primary model, the helper links, permissions and safety limits. Read-only.",
      parameters: {},
      implementation: async () => {
        try {
          const st = await readState();
          const loaded = (await listLoadedHandles(client)).map((h) => handleKeys(h)[0]);
          return {
            status: "ok",
            primary: st.primary,
            links: st.links,
            loaded_models: loaded,
            safety: st.safety,
            note: "Angra never loads, unloads or selects models. The user controls everything.",
          };
        } catch (e) {
          return denied("state_unavailable", "Angra state is unreadable: " + String(e));
        }
      },
    }),
  );

  tools.push(
    tool({
      name: "angra_list_loaded_models",
      description:
        "List models currently loaded in LM Studio, with Angra roles (primary/helper) and whether the user authorized them. Read-only.",
      parameters: {},
      implementation: async () => {
        try {
          const st = await readState();
          const helpers = new Set(Object.values(st.links).flat());
          const out = (await listLoadedHandles(client)).map((h) => {
            const key = handleKeys(h)[0];
            const isHelper = [...helpers].some((k) => sameModel(h, k));
            const permKey = Object.keys(st.permissions).find((k) => sameModel(h, k));
            return {
              model: key,
              is_primary: st.primary ? sameModel(h, st.primary) : false,
              is_linked_helper: isHelper,
              authorized: permKey ? permissionOk(st.permissions[permKey]).ok : false,
            };
          });
          return { status: "ok", loaded: out };
        } catch (e) {
          return denied("unavailable", "Could not list loaded models: " + String(e));
        }
      },
    }),
  );

  tools.push(
    tool({
      name: "angra_list_connections",
      description:
        "List the user-defined primary -> helper connections and whether each is currently usable. Read-only.",
      parameters: {},
      implementation: async () => {
        try {
          const st = await readState();
          const handles = await listLoadedHandles(client);
          const conns: unknown[] = [];
          for (const [primary, helpers] of Object.entries(st.links)) {
            for (const helper of helpers) {
              const loaded = handles.some((h) => sameModel(h, helper));
              const permKey = Object.keys(st.permissions).find((k) => k.toLowerCase() === helper.toLowerCase());
              const perm = permissionOk(permKey ? st.permissions[permKey] : undefined);
              conns.push({
                primary,
                helper,
                helper_loaded: loaded,
                permission: perm.mode,
                state: !loaded ? "paused_not_loaded" : perm.ok ? "connected" : "linked_not_authorized",
              });
            }
          }
          return { status: "ok", connections: conns };
        } catch (e) {
          return denied("unavailable", "Could not read connections: " + String(e));
        }
      },
    }),
  );

  tools.push(
    tool({
      name: "angra_consult_model",
      description:
        "Ask ONE already-loaded, user-authorized helper model a specific question. Send only the task and the minimal relevant context, never the whole conversation. Call at most once per answer. Returns the helper's short reply for you to use in your own final answer.",
      parameters: {
        model: z.string().describe("Name/key of the helper model, exactly as the user linked it."),
        task: z.string().describe("The specific question or task for the helper."),
        context: z.string().optional().describe("Only the minimal relevant context (code excerpt, facts)."),
      },
      implementation: async ({ model, task, context }, ctx: any) => {
        const requested = String(model ?? "").trim();
        if (!requested || requested.length > 200) {
          return denied("bad_request", "Invalid model name.");
        }
        if (!String(task ?? "").trim()) {
          return denied("bad_request", "A task is required.");
        }

        let st: AngraState;
        try {
          st = await readState();
        } catch (e) {
          await logEvent("consult_denied", { reason: "state_unavailable" });
          return denied("state_unavailable", "Angra state is unreadable; failing closed.");
        }
        const safety = st.safety;

        // Anti-recursion / anti-parallel guards (v1: always enforced).
        if (busy) {
          await logEvent("consult_denied", { reason: "busy", model: requested });
          return denied("busy", "Another helper call is in progress. Parallel helper calls are disabled.");
        }
        const sinceLast = (Date.now() - lastCallAt) / 1000;
        if (lastCallAt > 0 && sinceLast < safety.cooldown_seconds) {
          await logEvent("consult_denied", { reason: "cooldown", model: requested });
          return denied(
            "cooldown",
            "Helper cooldown active (" + safety.cooldown_seconds + "s). Only one helper call per answer is allowed.",
          );
        }

        busy = true;
        try {
          if (!st.primary) {
            return denied("no_primary", "The user has not declared a primary model (angra primary <model>).");
          }

          // FIRST: enumerate models that are already loaded. SECOND: verify.
          const handles = await listLoadedHandles(client);
          const primaryLoaded = handles.some((h) => sameModel(h, st.primary as string));
          if (!primaryLoaded) {
            await logEvent("consult_denied", { reason: "primary_not_loaded", model: requested });
            return denied("primary_paused", "The declared primary model is not loaded. Connection is paused.");
          }
          const helperHandle = handles.find((h) => sameModel(h, requested));
          if (!helperHandle) {
            await logEvent("consult_denied", { reason: "not_loaded", model: requested });
            return denied(
              "not_loaded",
              "MODEL NOT LOADED. Angra will not load it. Ask the user to load it manually in LM Studio.",
            );
          }

          const linked = (st.links[st.primary] ?? []).find((k) => sameModel(helperHandle, k));
          if (!linked) {
            await logEvent("consult_denied", { reason: "not_linked", model: requested });
            return denied("not_linked", "No user-created link from the primary to this helper (angra link).");
          }
          if (sameModel(helperHandle, st.primary)) {
            return denied("self_call", "A model cannot consult itself.");
          }

          const permKey = Object.keys(st.permissions).find((k) => k.toLowerCase() === linked.toLowerCase());
          const perm = permissionOk(permKey ? st.permissions[permKey] : undefined);
          if (!perm.ok) {
            await logEvent("consult_denied", { reason: "no_permission", model: linked, mode: perm.mode });
            return denied("no_permission", "HELPER CALL DENIED: the user has not authorized this helper (angra allow).");
          }

          // Bounded context: reject instead of silently shipping more.
          const maxChars = Math.max(256, safety.max_helper_context * 4);
          const taskText = String(task);
          const ctxText = String(context ?? "");
          if (taskText.length + ctxText.length > maxChars) {
            await logEvent("consult_denied", { reason: "context_too_large", model: linked });
            return denied(
              "context_too_large",
              "Task+context exceed the helper limit (" + maxChars + " characters). Send less.",
            );
          }

          // Fail closed if a one-time permission cannot be consumed.
          if (perm.mode === "once") {
            try {
              await consumeOnce(permKey as string);
            } catch (e) {
              return denied("no_permission", "Could not consume one-time permission: " + String(e));
            }
          }

          const controller = new AbortController();
          const timer = setTimeout(() => controller.abort(), safety.timeout_seconds * 1000);
          const outer: AbortSignal | undefined = ctx?.signal;
          if (outer) outer.addEventListener("abort", () => controller.abort());

          await logEvent("consult_start", { model: linked, mode: perm.mode });
          try {
            const userContent = ctxText.trim()
              ? "Task:\n" + taskText + "\n\nRelevant context:\n" + ctxText
              : "Task:\n" + taskText;
            const result = await (helperHandle as any).respond(
              [
                {
                  role: "system",
                  content:
                    "You are a helper model consulted by another model. Answer only the specific task, concisely. Do not ask questions back.",
                },
                { role: "user", content: userContent },
              ],
              { maxTokens: safety.max_helper_output, signal: controller.signal },
            );
            lastCallAt = Date.now();
            const text = String(result?.content ?? "").slice(0, safety.max_helper_output * 8);
            await logEvent("consult_done", { model: linked, chars: text.length });
            return {
              model: linked,
              status: "completed",
              analysis: text,
              warnings: [] as string[],
              inference_owner: "LM Studio",
              angra_inference: "none",
            };
          } catch (e) {
            lastCallAt = Date.now();
            const aborted = controller.signal.aborted;
            await logEvent("consult_error", { model: linked, aborted });
            return denied(aborted ? "timeout_or_aborted" : "helper_error", aborted ? "Helper call timed out or was aborted." : "Helper call failed: " + String(e));
          } finally {
            clearTimeout(timer);
          }
        } catch (e) {
          await logEvent("consult_error", { reason: "unexpected" });
          return denied("error", "Unexpected error: " + String(e));
        } finally {
          busy = false;
        }
      },
    }),
  );

  return tools;
}
'''


