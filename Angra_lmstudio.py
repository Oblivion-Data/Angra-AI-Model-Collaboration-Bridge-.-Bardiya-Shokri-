class Report:
    def __init__(self) -> None:
        self.rows: List[Tuple[str, str, str]] = []

    def add(self, level: str, name: str, detail: str = "") -> None:
        self.rows.append((level, name, detail))

    def count(self, level: str) -> int:
        return sum(1 for r in self.rows if r[0] == level)

    def print(self) -> None:
        for level, name, detail in self.rows:
            print("%s %-22s %s" % (level_tag(level), name, detail))
        print("\n%d passed, %d warnings, %d failed" % (self.count("PASS"), self.count("WARN"), self.count("FAIL")))


def lms_dev_install_capable(lms: str) -> Tuple[bool, str]:
    rc, out, err = run([lms, "dev", "--help"], timeout=20)
    text = out + err
    if rc != 0:
        return False, "`lms dev --help` failed"
    if "--install" in text or " -i," in text or "install" in text.lower():
        return True, "`lms dev --install` available"
    return False, "`lms dev` has no install option in this version"


def run_doctor(app: App) -> Report:
    r = Report()
    r.add("PASS" if os.name == "nt" else "FAIL", "Windows", sys.platform if os.name != "nt" else "Windows detected")
    r.add("PASS" if sys.version_info >= (3, 8) else "FAIL", "Python", sys.version.split()[0])
    app_path = find_lmstudio_app()
    r.add("PASS" if app_path else "WARN", "LM Studio", app_path or "application not located (lms may still work)")
    lms = app.lms()
    if lms:
        rc, _, err = run([lms, "--help"], timeout=20)
        r.add("PASS" if rc == 0 else "FAIL", "lms CLI", lms if rc == 0 else "`lms --help` failed: " + err.strip()[:120])
    else:
        r.add("FAIL", "lms CLI", "not found. Run LM Studio once, then `lms bootstrap`")
    if lms:
        ok, msg = lms_dev_install_capable(lms)
        r.add("PASS" if ok else "WARN", "Plugin support", msg)
    else:
        r.add("FAIL", "Plugin support", "requires lms")
    st = app.state()
    ok, msg = plugin_status(app, st)
    r.add("PASS" if ok else "WARN", "Plugin installation", msg)
    snap = app.snapshot(refresh=True)
    r.add("PASS" if snap.ls_ok else "FAIL", "Model discovery",
          "%d model(s)" % len(snap.models) if snap.ls_ok else "lms ls --json unavailable")
    loaded = [m for m in snap.models if m.loaded]
    r.add("PASS" if snap.ps_ok else "WARN", "Loaded models",
          "%d loaded" % len(loaded) if snap.ps_ok else "lms ps --json unavailable (LM Studio running?)")
    dirs_ok = all(p.is_dir() for p in (app.home, app.bin_dir, app.home / "logs"))
    r.add("PASS" if dirs_ok else "WARN", "Angra directories", str(app.home))
    cfgp = app.home / "config.json"
    try:
        json.loads(cfgp.read_text(encoding="utf-8"))
        r.add("PASS", "Configuration", str(cfgp))
    except (OSError, ValueError):
        r.add("WARN", "Configuration", "missing or invalid (angra repair)")
    sp = app.store.path
    try:
        json.loads(sp.read_text(encoding="utf-8"))
        r.add("PASS", "State", "%s (schema %d)" % (sp, st["schema"]))
    except (OSError, ValueError):
        r.add("WARN", "State", "missing or invalid (angra repair)")
    exp = launcher_text(sys.executable, app.script_copy)
    if app.launcher.is_file():
        same = app.launcher.read_bytes() == encode_launcher(exp)
        r.add("PASS" if same else "WARN", "Launcher", str(app.launcher) if same else "present but modified (angra repair)")
    else:
        r.add("WARN", "Launcher", "angra.cmd missing (angra install / repair)")
    if winreg is None:
        r.add("SKIP", "PATH", "Windows only")
    else:
        try:
            has = user_path_has(str(app.bin_dir))
            r.add("PASS" if has else "WARN", "PATH", "user PATH contains launcher dir" if has else "launcher dir not on user PATH")
        except OSError as e:
            r.add("FAIL", "PATH", str(e))
    try:
        app.home.mkdir(parents=True, exist_ok=True)
        t = app.home / (".write-test-%s" % uuid.uuid4().hex[:6])
        t.write_text("x")
        t.unlink()
        r.add("PASS", "Filesystem", "Angra directory is writable")
    except OSError as e:
        r.add("FAIL", "Filesystem", str(e))
    return r


FORBIDDEN_IN_PLUGIN = (".load(", ".model(", "unload(", "lms load", "load_new_instance", "downloadModel")


def run_self_test(app: App) -> Report:
    r = Report()
    # terminal rendering
    try:
        logo = render_logo()
        r.add("PASS" if logo and len({len(l) for l in logo}) >= 1 else "FAIL", "Terminal render", "%d logo lines" % len(logo))
    except Exception as e:  # pragma: no cover
        r.add("FAIL", "Terminal render", str(e))
    # CLI + JSON + filesystem + state
    with tempfile.TemporaryDirectory(prefix="angra-selftest-") as td:
        tdp = Path(td)
        try:
            s = Store(tdp / "state.json")
            st = default_state()
            st["links"] = {"a": ["b"]}
            s.save(st)
            back = s.load()
            r.add("PASS" if back["links"] == {"a": ["b"]} and back["helpers"] == ["b"] else "FAIL", "JSON/state", "atomic write + reload")
        except Exception as e:
            r.add("FAIL", "JSON/state", str(e))
        try:
            atomic_write(tdp / "x.bin", b"1")
            atomic_write(tdp / "x.bin", b"2")
            r.add("PASS" if (tdp / "x.bin").read_bytes() == b"2" else "FAIL", "Filesystem", "atomic replace")
        except Exception as e:
            r.add("FAIL", "Filesystem", str(e))
        # plugin generation
        try:
            files = plugin_files(tdp)
            for rel, content in files.items():
                atomic_write_text(tdp / "plug" / rel, content)
            json.loads((tdp / "plug" / "manifest.json").read_text())
            json.loads((tdp / "plug" / "package.json").read_text())
            json.loads((tdp / "plug" / "tsconfig.json").read_text())
            ts = files["src/toolsProvider.ts"] + files["src/index.ts"]
            bad = [f for f in FORBIDDEN_IN_PLUGIN if f in ts]
            needed = ["listLoaded", "angra_status", "angra_list_loaded_models", "angra_list_connections", "angra_consult_model"]
            miss = [n for n in needed if n not in ts]
            if bad:
                r.add("FAIL", "Plugin generation", "forbidden call(s) present: %s" % bad)
            elif miss:
                r.add("FAIL", "Plugin generation", "missing: %s" % miss)
            else:
                r.add("PASS", "Plugin generation", "%d files, no load/unload calls" % len(files))
        except Exception as e:
            r.add("FAIL", "Plugin generation", str(e))
        try:
            lt = launcher_text("C:\\Program Files\\Python\\python.exe", Path("C:\\Users\\a b\\Angra.py"))
            ok = '"C:\\Program Files\\Python\\python.exe"' in lt and "%*" in lt and "ERRORLEVEL" in lt
            r.add("PASS" if ok else "FAIL", "Launcher", "quoting, %*, exit code")
        except Exception as e:
            r.add("FAIL", "Launcher", str(e))
    # permissions
    st = default_state()
    now = 1000.0
    st["permissions"] = {
        "on": {"mode": "enabled"}, "off": {"mode": "off"},
        "s1": {"mode": "session", "expires_at": now + 10}, "s0": {"mode": "session", "expires_at": now - 1},
        "o": {"mode": "once"},
    }
    ok = (perm_effective(st, "on", now)[1] and not perm_effective(st, "off", now)[1]
          and perm_effective(st, "s1", now)[1] and not perm_effective(st, "s0", now)[1]
          and perm_effective(st, "o", now)[1] and not perm_effective(st, "missing", now)[1])
    r.add("PASS" if ok else "FAIL", "Permissions", "off/once/session/enabled/expiry")
    # connection graph
    g = default_state()
    g["links"] = {"P": ["H"]}
    checks = [graph_add_error(g, "P", "P") is not None, graph_add_error(g, "H", "P") is not None,
              graph_add_error(g, "H", "X") is not None, graph_add_error(g, "P", "Y") is None,
              graph_add_error(g, "Q", "H") is None]
    r.add("PASS" if all(checks) else "FAIL", "Connection graph", "self-loops, cycles and chains rejected")
    # safety invariants
    sf = sanitize_safety({"parallel_helpers": True, "recursive_delegation": True, "max_active_helpers": 9,
                          "max_helper_calls_per_response": 5})
    inv = (sf["parallel_helpers"] is False and sf["recursive_delegation"] is False
           and sf["max_active_helpers"] == 1 and sf["max_helper_calls_per_response"] == 1)
    r.add("PASS" if inv else "FAIL", "Safety invariants", "parallel/recursion cannot be enabled")
    # discovery
    lms = app.lms()
    if not lms:
        for n in ("LM Studio discovery", "lms", "Model discovery", "Loaded discovery"):
            r.add("WARN", n, "lms CLI not found")
    else:
        r.add("PASS", "lms", lms)
        snap = app.snapshot(refresh=True)
        r.add("PASS" if (snap.ls_ok or snap.ps_ok) else "WARN", "LM Studio discovery",
              "reachable" if (snap.ls_ok or snap.ps_ok) else "not reachable")
        r.add("PASS" if snap.ls_ok else "WARN", "Model discovery", "%d model(s)" % len(snap.models))
        r.add("PASS" if snap.ps_ok else "WARN", "Loaded discovery", "%d loaded" % sum(m.loaded for m in snap.models))
    # PATH (read-only)
    if winreg is None:
        r.add("SKIP", "PATH", "Windows only")
    else:
        try:
            user_path_read()
            r.add("PASS", "PATH", "user PATH readable")
        except OSError as e:
            r.add("FAIL", "PATH", str(e))
    return r


