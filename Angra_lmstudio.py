class App:
    def __init__(self) -> None:
        self.home = angra_home()
        self.cfg = load_config(self.home)
        self.store = Store(self.home / "state.json")
        self._snap: Optional[Snapshot] = None

    @property
    def plugin_dir(self) -> Path:
        return self.home / "plugin" / PLUGIN_NAME

    @property
    def bin_dir(self) -> Path:
        return self.home / "bin"

    @property
    def launcher(self) -> Path:
        return self.bin_dir / "angra.cmd"

    @property
    def script_copy(self) -> Path:
        return self.home / "Angra.py"

    def lms(self) -> Optional[str]:
        return find_lms(self.cfg)

    def snapshot(self, refresh: bool = False) -> Snapshot:
        if self._snap is None or refresh:
            self._snap = discover(self.lms())
        return self._snap

    def state(self) -> dict:
        return self.store.load()

    def resolve(self, query: str, st: Optional[dict] = None) -> Model:
        q = validate_name(query).lower()
        snap = self.snapshot()
        exact = [m for m in snap.models if q in m.aliases()]
        if len(exact) == 1:
            return exact[0]
        part = exact or [m for m in snap.models if any(q in a for a in m.aliases())]
        if len(part) == 1:
            return part[0]
        if len(part) > 1:
            raise UserError("Ambiguous model name '%s'. Matches:" % query, ["  - " + m.name for m in part])
        if not snap.ls_ok:
            st = st or self.state()
            known = set(st["links"]) | {h for hs in st["links"].values() for h in hs} | set(st["permissions"])
            if st["primary"]:
                known.add(st["primary"])
            for k in known:
                if k.lower() == q:
                    return Model(key=k, name=k)
        lines = ["", "Available models:"] + ["  - " + m.name for m in snap.models] if snap.models else \
            ["", "No models could be discovered (is LM Studio running and lms available?)."]
        raise UserError("Unknown model '%s'." % query, lines)

    def expected_plugin_state(self) -> Tuple[List[str], List[str]]:
        """(missing, modified) among Angra-owned plugin files."""
        missing, modified = [], []
        for rel, content in plugin_files(self.home).items():
            p = self.plugin_dir / rel
            if not p.is_file():
                missing.append(rel)
            elif p.read_bytes() != content.encode("utf-8"):
                modified.append(rel)
        if not (self.plugin_dir / PLUGIN_MARKER).is_file():
            missing.append(PLUGIN_MARKER)
        return missing, modified


