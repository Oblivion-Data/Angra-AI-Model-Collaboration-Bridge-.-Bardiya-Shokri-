"""
ANGRA - user-controlled local model bridge for LM Studio (Windows).

Two products live in this design (kept explicit on purpose):

  A) Angra.py            - THIS file. Dependency-free Python (standard library
                           only). It is the installer, the control CLI and the
                           owner of Angra's state. It never runs a model.
  B) The generated plugin - an official LM Studio *tools provider* plugin
                           (TypeScript, runs on LM Studio's own Node runtime,
                           uses LM Studio's own @lmstudio/sdk). Angra.py writes
                           its files from templates embedded below and
                           registers it with the official `lms dev --install`.

Principle:  USER CHOOSES.  LM STUDIO RUNS THE MODELS.  ANGRA CONNECTS THEM.

Hard invariants: Angra never loads, downloads, unloads, switches or routes
models; never patches LM Studio; never performs inference; never starts a
server. The generated plugin only obtains handles for models that are already
loaded (it enumerates loaded models first) and never calls a load operation.
"""
