def rule() -> str:
    return ("\u2500" if T.blocks else "-") * 56


def dot(kind: str) -> str:
    ch = "\u25cf" if T.dot else "*"
    col = {"ok": "green", "bad": "red", "warn": "yellow"}[kind]
    return paint(ch, col)


def level_tag(level: str) -> str:
    col = {"PASS": "green", "WARN": "yellow", "FAIL": "red", "SKIP": "grey"}[level]
