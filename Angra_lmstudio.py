class UserError(Exception):
    def __init__(self, title: str, lines: Optional[List[str]] = None):
        super().__init__(title)
        self.title = title
        self.lines = lines or []


def print_error(e: UserError) -> None:
    print(paint("ERROR", "red", "bold"))
    print(e.title)
    for ln in e.lines:
        print(ln)


