def cmd_status(app: App) -> int:
    st, snap = app.state(), app.snapshot(refresh=True)
    online = snap.ls_ok or snap.ps_ok
    plug_ok, plug_msg = plugin_status(app, st)
    print("LM Studio : %s" % ("ONLINE" if online else "OFFLINE / lms unavailable"))
    print("lms CLI   : %s" % (app.lms() or "not found"))
    print("Plugin    : %s (%s)" % ("INSTALLED" if plug_ok else "NOT READY", plug_msg))
    names = {m.key: m.name for m in snap.models}
    print("Primary   : %s" % (names.get(st["primary"], st["primary"]) if st["primary"] else "(not set)"))
    n = sum(len(v) for v in st["links"].values())
    print("Links     : %d" % n)
    s = st["safety"]
    print("Safety    : helpers=%d parallel=%s calls/response=%d recursion=%s ctx=%d out=%d timeout=%ds" % (
        s["max_active_helpers"], s["parallel_helpers"], s["max_helper_calls_per_response"],
        s["recursive_delegation"], s["max_helper_context"], s["max_helper_output"], s["timeout_seconds"]))
    print("Inference : LM Studio only. Angra inference: NONE")
    return 0


def cmd_primary(app: App, args: List[str]) -> int:
    if len(args) != 1:
        raise UserError("Usage: angra primary \"<model>\"")
    st = app.state()
    m = app.resolve(args[0], st)
    if any(m.key in hs for hs in st["links"].values()):
        raise UserError("'%s' is a helper; helper chains are disabled." % m.name,
                        ["Unlink it first if you want it to be the primary."])
    st["primary"] = m.key
    app.store.save(st)
    log.info("primary set: %s", m.key)
    print("Primary model recorded: %s" % m.name)
    print("Angra did not change anything in LM Studio. Select/load your primary there yourself.")
    if not m.loaded:
        print(paint("Note: this model is not currently loaded.", "yellow"))
    return 0


def _require_loaded(m: Model) -> None:
    if not m.loaded:
        raise UserError("REQUEST DENIED", [
            "", "%s is installed but not loaded in LM Studio." % m.name, "",
            "Angra will NOT load it automatically.", "Load the model manually in LM Studio first.",
            "Then run the command again."])


def cmd_link(app: App, args: List[str]) -> int:
    if len(args) != 2:
        raise UserError("Usage: angra link \"<primary>\" \"<helper>\"")
    st = app.state()
    p, h = app.resolve(args[0], st), app.resolve(args[1], st)
    _require_loaded(h)
    err = graph_add_error(st, p.key, h.key)
    if err:
        raise UserError("LINK REFUSED", [err])
    if h.key in st["links"].get(p.key, []):
        raise UserError("Link already exists.", ["%s -> %s" % (p.name, h.name)])
    st["links"].setdefault(p.key, []).append(h.key)
    if not st["primary"]:
        st["primary"] = p.key
    app.store.save(st)
    log.info("link added: %s -> %s", p.key, h.key)
    print("LINK CREATED\n\n  %s\n      |\n      +----> %s\n" % (p.name, h.name))
    print("Nothing was loaded or started. The helper still needs permission: angra allow \"%s\"" % h.name)
    if st["primary"] != p.key:
        print(paint("Note: your declared primary is a different model; run: angra primary \"%s\"" % p.name, "yellow"))
    return 0


def cmd_unlink(app: App, args: List[str]) -> int:
    if len(args) != 2:
        raise UserError("Usage: angra unlink \"<primary>\" \"<helper>\"")
    st = app.state()
    p, h = app.resolve(args[0], st), app.resolve(args[1], st)
    if h.key not in st["links"].get(p.key, []):
        raise UserError("No such link.", ["%s -> %s" % (p.name, h.name)])
    st["links"][p.key].remove(h.key)
    app.store.save(st)
    log.info("link removed: %s -> %s", p.key, h.key)
    print("Link removed: %s -> %s" % (p.name, h.name))
    return 0


def cmd_connect(app: App, args: List[str]) -> int:
    if len(args) != 1:
        raise UserError("Usage: angra connect \"<model>\"")
    st = app.state()
    if not st["primary"]:
        raise UserError("No primary model set.", ["Run: angra primary \"<model>\" first."])
    h = app.resolve(args[0], st)
    _require_loaded(h)
    err = graph_add_error(st, st["primary"], h.key)
    if err:
        raise UserError("CONNECTION REFUSED", [err])
    names = {m.key: m.name for m in app.snapshot().models}
    if h.key not in st["links"].get(st["primary"], []):
        st["links"].setdefault(st["primary"], []).append(h.key)
        app.store.save(st)
    log.info("connect: %s -> %s", st["primary"], h.key)
    state = "CONNECTED" if perm_effective(st, h.key)[1] else "LINKED (waiting for your permission)"
    print("CONNECTION ESTABLISHED\n\nPrimary:\n%s\n\nHelper:\n%s\n\nState:\n%s\n" % (
        names.get(st["primary"], st["primary"]), h.name, state))
    print("Inference owner: LM Studio\nAngra inference: NONE")
    if not perm_effective(st, h.key)[1]:
        print("\nAuthorize it with: angra allow \"%s\" [--once|--session]" % h.name)
    return 0


def cmd_disconnect(app: App, args: List[str]) -> int:
    if len(args) != 1:
        raise UserError("Usage: angra disconnect \"<model>\"")
    st = app.state()
    h = app.resolve(args[0], st)
    removed = 0
    for hs in st["links"].values():
        while h.key in hs:
            hs.remove(h.key)
            removed += 1
    st["permissions"].pop(h.key, None)
    app.store.save(st)
    log.info("disconnect: %s (links removed=%d)", h.key, removed)
    print("Disconnected %s (links removed: %d, permission revoked)." % (h.name, removed))
    return 0


def cmd_allow(app: App, args: List[str]) -> int:
    flags = [a for a in args if a.startswith("--")]
    rest = [a for a in args if not a.startswith("--")]
    if len(rest) != 1 or any(f not in ("--once", "--session") for f in flags) or len(flags) > 1:
        raise UserError("Usage: angra allow \"<model>\" [--once | --session]")
    st = app.state()
    m = app.resolve(rest[0], st)
    if st["primary"] == m.key:
        raise UserError("The primary model cannot be authorized as a helper.")
    if flags == ["--once"]:
        entry = {"mode": "once", "granted_at": now_iso(), "expires_at": None}
    elif flags == ["--session"]:
        ttl = float(app.cfg.get("session_ttl_hours", 4))
        entry = {"mode": "session", "granted_at": now_iso(), "expires_at": time.time() + ttl * 3600}
    else:
        entry = {"mode": "enabled", "granted_at": now_iso(), "expires_at": None}
    st["permissions"][m.key] = entry
    app.store.save(st)
    log.info("permission: %s -> %s", m.key, entry["mode"])
    print("Permission for %s: %s" % (m.name, entry["mode"].upper()))
    if entry["mode"] == "session":
        print("Valid for %s hour(s)." % app.cfg.get("session_ttl_hours", 4))
    if not any(m.key in hs for hs in st["links"].values()):
        print(paint("It is not linked yet: angra link \"<primary>\" \"%s\"" % m.name, "yellow"))
    return 0


def cmd_deny(app: App, args: List[str]) -> int:
    if len(args) != 1:
        raise UserError("Usage: angra deny \"<model>\"")
    st = app.state()
    m = app.resolve(args[0], st)
    st["permissions"][m.key] = {"mode": "off", "granted_at": None, "expires_at": None}
    app.store.save(st)
    log.info("permission: %s -> off", m.key)
    print("Permission for %s: OFF (helper calls will be DENIED)" % m.name)
    return 0


